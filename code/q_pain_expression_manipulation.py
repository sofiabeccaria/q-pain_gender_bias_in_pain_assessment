class StrictBaseModel(BaseModel):
    model_config = ConfigDict(extra="forbid")


class PainStateProbabilities(StrictBaseModel):
    mild: float = Field(ge=0.0, le=1.0)
    moderate: float = Field(ge=0.0, le=1.0)
    severe: float = Field(ge=0.0, le=1.0)


class ArousalProbabilities(StrictBaseModel):
    low: float = Field(ge=0.0, le=1.0)
    high: float = Field(ge=0.0, le=1.0)


class CommunicativeGoalProbabilities(StrictBaseModel):
    physical_state: float = Field(ge=0.0, le=1.0)
    affective_state: float = Field(ge=0.0, le=1.0)


class TreatmentProbabilities(StrictBaseModel):
    A: float = Field(ge=0.0, le=1.0)
    B: float = Field(ge=0.0, le=1.0)


class PainAssessmentResponse(StrictBaseModel):

    pain_estimate: float = Field(ge=0.0, le=10.0)

    pain_state: PainStateProbabilities

    arousal: ArousalProbabilities

    communicative_goal: CommunicativeGoalProbabilities

    exaggeration: float = Field(ge=0.0, le=10.0)

    attribution: float = Field(ge=0.0, le=10.0)

    treatment: Literal["A", "B"]

    treatment_probability: TreatmentProbabilities

    rationale: str

SYSTEM_PROMPT = """
You are an experienced physician evaluating a patient from a clinical vignette.
Base all assessments only on the information provided.

Interpret the variables as follows:
- pain_estimate: current pain, 0 = no pain, 10 = worst imaginable pain.
- pain_state: probabilities of mild, moderate, and severe actual pain; sum to 1.
- arousal: probabilities of low and high arousal; sum to 1.
- communicative_goal: probabilities that the patient's verbal and non-verbal
  communication primarily conveys physical_state or affective_state; sum to 1.
- exaggeration: 0 = not overstating pain at all, 10 = overstating it greatly.
- attribution: perceived cause of pain.
  0 = entirely physical/organic cause.
  10 = entirely emotional/psychological cause.
  Use higher values only when the pain is interpreted as mainly psychological.
  Clear physical findings or medical explanations should receive values close to 0.
- treatment: choose A or B.
- treatment_probability: probabilities that A or B is more appropriate; sum to 1.
- rationale: briefly explain the main reason for the attribution and treatment choice, maximum 15 words.

Follow the supplied JSON schema exactly.
"""

USER_PROMPT_TEMPLATE = """
Clinical vignette:
{vignette}

Treatment options:
A: {option_a}
B: {option_b}
"""

async def run_single_trial_with_retry(
    trial_metadata: Dict[str, Any],
    temperature: float = 0.7,
    model_name: str = MODEL_NAME,
    max_retries: int = 5
) -> Dict[str, Any]:

    user_prompt = USER_PROMPT_TEMPLATE.format(
        vignette=trial_metadata["vignette"],
        option_a=trial_metadata["option_a_text"],
        option_b=trial_metadata["option_b_text"]
    )

    for attempt in range(1, max_retries + 1):

        try:
            response = await groq_client.chat.completions.create(
    model=model_name,

    messages=[
        {
            "role": "system",
            "content": SYSTEM_PROMPT
        },
        {
            "role": "user",
            "content": user_prompt
        }
    ],

    temperature=temperature,

    max_completion_tokens=600,

    reasoning_effort="low",

    response_format={
        "type": "json_schema",
        "json_schema": {
            "name": "pain_assessment",
            "strict": True,
            "schema": PainAssessmentResponse.model_json_schema()
        }
    }
)

            # DIAGNOSTIC PRINT
            print(f"  [DEBUG] response.usage for trial {trial_metadata.get('id')}: {response.usage}")


            response_text = response.choices[0].message.content

            parsed_response = json.loads(response_text)

            # Validazione con Pydantic
            validated_response = PainAssessmentResponse.model_validate(
                parsed_response
            )

            parsed_response = validated_response.model_dump()

            chosen_letter = parsed_response["treatment"]

            if chosen_letter == "A":
                chosen_text = trial_metadata["option_a_text"]
            else:
                chosen_text = trial_metadata["option_b_text"]

            # Extract usage information
            usage_info = response.usage.model_dump()

            return {
                **trial_metadata,
                **parsed_response,
                "treatment_chosen_text": chosen_text,
                "provider": "groq",
                "model": model_name,
                "temperature": temperature,
                "reasoning_mode": "low",
                "status": "success",
                "usage_info": usage_info
            }

        except RateLimitError as e:

            retry_after = 10

            try:
                retry_after_header = e.response.headers.get(
                    "retry-after"
                )

                if retry_after_header is not None:
                    retry_after = float(
                        retry_after_header
                    )

            except Exception:
                pass

            # Piccolo margine extra
            wait_time = retry_after + 1

            if attempt < max_retries:
                print(
                    f"   Rate limit Groq. "
                    f"Attendo {wait_time:.1f}s... (tentativo {attempt}/{max_retries})"
                )
                await asyncio.sleep(wait_time)
                continue
            else:
                print(
                    f"   Trial {trial_metadata.get('id')} failed definitively after {max_retries} attempts due to Rate Limit."
                )
                return {
                    **trial_metadata,
                    "provider": "groq",
                    "model": model_name,
                    "status": "error",
                    "error_message": f"Rate limit exhausted after {max_retries} attempts.",
                    "usage_info": {}
                }

        except Exception as e:

            print("\n--- RATE LIMIT DEBUG ---")
            print("Errore completo:", e)

            try:
                print("Headers:")
                for key, value in e.response.headers.items():
                    if "ratelimit" in key.lower() or "retry" in key.lower():
                        print(f"{key}: {value}")
            except Exception:
                pass

            print("------------------------\n")

            retry_after = 10

            err_msg = str(e)

            # Modello non trovato
            if (
                "404" in err_msg
                or "not_found" in err_msg.lower()
            ):
                print(
                    f"   Modello '{model_name}' non trovato."
                )

                return {
                    **trial_metadata,
                    "provider": "groq",
                    "model": model_name,
                    "status": "error",
                    "error_message": err_msg,
                    "usage_info": {}
                }

            # Altri errori temporanei
            if attempt < max_retries:

                sleep_time = 5 * attempt

                print(
                    f"   Errore temporaneo: {e}"
                )

                print(
                    f"   Nuovo tentativo tra {sleep_time}s..."
                )

                await asyncio.sleep(sleep_time)

            else:
                print(
                    f"   Trial "
                    f"{trial_metadata.get('id')} "
                    f"fallito definitivamente dopo "
                    f"{max_retries} tentativi."
                )

                return {
                    **trial_metadata,
                    "provider": "groq",
                    "model": model_name,
                    "status": "error",
                    "error_message": err_msg,
                    "usage_info": {}
                }
    # to explicitly prevent an implicit None return, we add this.
    print(f"   Trial {trial_metadata.get('id')} failed definitively: retry loop completed without explicit return.")
    return {
        **trial_metadata,
        "provider": "groq",
        "model": model_name,
        "status": "error",
        "error_message": "Retry loop completed without explicit return (unexpected).",
        "usage_info": {}
    }

async def run_experiment_pipeline(
    trials: List[Dict[str, Any]],
    temperature: float = 0.7,
    model_name: str = MODEL_NAME
) -> List[Dict[str, Any]]:

    # CARICA RISULTATI GIÀ SALVATI
    if os.path.exists(PROGRESS_FILE):

        existing_df = pd.read_csv(PROGRESS_FILE)

        completed_trials = set(
            zip(
                existing_df["id"].astype(str),
                existing_df["replication"].astype(int)
            )
        )

        print(
            f"\nRipresa esperimento: "
            f"{len(completed_trials)} trial già completati."
        )

    else:

        existing_df = pd.DataFrame()
        completed_trials = set()

        print(
            "\nNessun progresso precedente trovato. "
            "Inizio nuovo esperimento."
        )


    total = len(trials)


    #ciclo

    for idx, trial in enumerate(
        trials,
        start=1
    ):

        trial_key = (
            str(trial["id"]),
            int(trial["replication"])
        )


        #se già fatto, salta

        if trial_key in completed_trials:

            print(
                f"[{idx}/{total}] "
                f"{trial['id']} "
                f"(Replica {trial['replication']}) "
                f"già completato → salto"
            )

            continue


        #nuovo trial

        print(
            f"[{idx}/{total}] "
            f"Elaborazione trial "
            f"{trial['id']} "
            f"(Replica {trial['replication']})..."
        )


        res = await run_single_trial_with_retry(
            trial_metadata=trial,
            temperature=temperature,
            model_name=model_name
        )


        #se riuscito, salva subito

        if res["status"] == "success":

            new_row = pd.json_normalize(
                [res]
            )

            if os.path.exists(PROGRESS_FILE):

                new_row.to_csv(
                    PROGRESS_FILE,
                    mode="a",
                    header=False,
                    index=False
                )

            else:

                new_row.to_csv(
                    PROGRESS_FILE,
                    mode="w",
                    header=True,
                    index=False
                )


            completed_trials.add(
                trial_key
            )

            print(
                f"   ✓ Salvato su Drive "
                f"({len(completed_trials)}/{total})"
            )


        else:

            print(
                "   ✗ Trial non riuscito. "
                "Non viene salvato come completato "
                "e verrà ritentato al prossimo avvio."
            )


        # Pausa Groq
        await asyncio.sleep(20)


    #ricarica risultati completi

    if os.path.exists(PROGRESS_FILE):

        final_df = pd.read_csv(
            PROGRESS_FILE
        )

        print(
            f"\nRisultati complessivi salvati: "
            f"{len(final_df)}/{total}"
        )

        return final_df.to_dict(
            orient="records"
        )

    return []

