class PainAssessmentResponse(BaseModel):
    pain_estimate: int = Field(..., ge=0, le=10)
    exaggeration: int = Field(..., ge=0, le=10)
    attribution: int = Field(..., ge=0, le=10)
    treatment: Literal["A", "B"]
    rationale: str

#prompt system e utente
SYSTEM_PROMPT = """You are an experienced physician evaluating patients in a clinical setting.
You will be shown a short clinical vignette followed by a set of questions.
Answer every question. Respond only with a JSON object matching the schema provided; do not include any text outside the JSON object."""

USER_PROMPT_TEMPLATE = """Clinical vignette:
{vignette}

Questions:
1. pain_estimate — On a scale from 0 to 10, how much pain is this patient currently experiencing? (0 = no pain, 10 = worst pain imaginable)
2. exaggeration — On a scale from 0 to 10, to what extent is this patient overstating their pain relative to what they are actually experiencing? (0 = not at all, 10 = to a great extent)
3. attribution — On a scale from 0 to 10, to what extent does this patient’s pain arise from emotional rather than physical causes? (0 = entirely physical, 10 = entirely emotional)
4. treatment — Which of the following do you consider more appropriate? Answer with a single letter.
   A: {option_a}
   B: {option_b}
5. rationale — Briefly explain your reasoning."""

async def run_single_trial_with_retry(
    trial_metadata: Dict[str, Any],
    temperature: float = 0.7,
    model_name: str = "qwen/qwen3.6-27b",
    max_retries: int = 5
) -> Dict[str, Any]:

    user_prompt = USER_PROMPT_TEMPLATE.format(
        vignette=trial_metadata["vignette"],
        option_a=trial_metadata["option_a_text"],
        option_b=trial_metadata["option_b_text"]
    )

    for attempt in range(1, max_retries + 1):

        try:
            response = await groq_client.chat.completions.create(
                model=model_name,

                messages=[
                    {
                        "role": "system",
                        "content": SYSTEM_PROMPT
                    },
                    {
                        "role": "user",
                        "content": user_prompt
                    }
                ],

                temperature=temperature,

                reasoning_effort= "none",
                # per groq qwen ="none",

                response_format={
                    "type": "json_object"
                }
            )

            response_text = response.choices[0].message.content

            parsed_response = json.loads(response_text)

            # Validazione con Pydantic
            validated_response = PainAssessmentResponse.model_validate(
                parsed_response
            )

            parsed_response = validated_response.model_dump()

            chosen_letter = parsed_response["treatment"]

            if chosen_letter == "A":
                chosen_text = trial_metadata["option_a_text"]
            else:
                chosen_text = trial_metadata["option_b_text"]

            return {
                **trial_metadata,
                **parsed_response,
                "treatment_chosen_text": chosen_text,
                "provider": "groq",
                "model": model_name,
                "temperature": temperature,
                "reasoning_mode": "none",
                "status": "success"
            }

        except Exception as e:

            err_msg = str(e)

            # se modello non trovato
            if (
                "404" in err_msg
                or "not_found" in err_msg.lower()
            ):
                print(
                    f" Modello '{model_name}' non trovato."
                )

                return {
                    **trial_metadata,
                    "provider": "groq",
                    "model": model_name,
                    "status": "error",
                    "error_message": err_msg
                }

            # se rate limit
            if (
                "429" in err_msg
                or "rate_limit" in err_msg.lower()
                or "rate limit" in err_msg.lower()
            ):
                if attempt < max_retries:

                    sleep_time = 20 * attempt

                    print(
                        f" Rate limit Groq. "
                        f"Pausa di {sleep_time}s "
                        f"(tentativo {attempt}/{max_retries})..."
                    )

                    await asyncio.sleep(sleep_time)
                    continue

            # Altri errori temporanei
            if attempt < max_retries:

                sleep_time = 5 * attempt

                print(
                    f" Errore temporaneo: {e}"
                )

                print(
                    f" Nuovo tentativo tra {sleep_time}s..."
                )

                await asyncio.sleep(sleep_time)

            else:
                print(
                    f"  Trial "
                    f"{trial_metadata.get('id')} "
                    f"fallito definitivamente dopo "
                    f"{max_retries} tentativi."
                )

                return {
                    **trial_metadata,
                    "provider": "groq",
                    "model": model_name,
                    "status": "error",
                    "error_message": err_msg
                }

#pipeline groq

async def run_experiment_pipeline(
    trials: List[Dict[str, Any]],
    temperature: float = 0.7,
    model_name: str = MODEL_NAME
) -> List[Dict[str, Any]]:

    results = []

    total = len(trials)

    for idx, trial in enumerate(
        trials,
        start=1
    ):

        print(
            f"[{idx}/{total}] "
            f"Elaborazione trial "
            f"{trial.get('id')} "
            f"(Replica "
            f"{trial.get('replication')})..."
        )

        res = await run_single_trial_with_retry(
            trial_metadata=trial,
            temperature=temperature,
            model_name=model_name
        )

        results.append(res)


        # SALVATAGGIO PROGRESSIVO

        # Se Colab si interrompe, non perdiamo tutte le risposte precedenti.

        partial_df = pd.DataFrame(results)

        partial_df.to_csv(
            "groq_qwen_partial_results.csv",
            index=False
        )

        # Piccola pausa per evitare rate limit
        await asyncio.sleep(3)

    return results

