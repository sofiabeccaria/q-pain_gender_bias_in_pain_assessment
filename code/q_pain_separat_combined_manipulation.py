def map_treatment(row):
    dec = str(row["decision"]).strip().upper()
    chosen_text = str(row["treatment_chosen"]).lower()
    if "opioid" in chosen_text:
        return "Trattamento Oppioide (Opioids)"
    elif "psychological" in chosen_text:
        return "Valutazione Psicologica (Psychological)"
    # Fallback basato sulla decisione standard se il testo non coincide
    if dec == "A":
        return "Trattamento Oppioide (A)"
    elif dec == "B":
        return "Valutazione Psicologica (B)"
