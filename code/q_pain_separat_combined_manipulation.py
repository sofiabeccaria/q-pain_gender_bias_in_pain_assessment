def call_openrouter(
    prompt,
    want_logprobs=False,
    max_tokens=256
):

    current_max_tokens = max_tokens


    for attempt in range(
        1,
        MAX_RETRIES + 1
    ):

        try:

            kwargs = {

                "model": MODEL,

                "messages": [
                    {
                        "role": "system",
                        "content": SYSTEM_PROMPT
                    },
                    {
                        "role": "user",
                        "content": prompt
                    }
                ],

                "temperature": TEMPERATURE,

                "max_tokens": current_max_tokens,
            }


            #log probs
            if want_logprobs:

                kwargs["logprobs"] = True
                kwargs["top_logprobs"] = 20


            response = client.chat.completions.create(

                **kwargs,

                extra_body={
                    "reasoning": {
                        "effort": "low",
                        "exclude": True
                    },

                    "provider": {
                        "require_parameters": True,
                        "allow_fallbacks": True
                    }
                }
            )

            print(response.model_dump_json(indent=2))

            #check risposta
            if not response.choices:

                raise RuntimeError(
                    "OpenRouter ha restituito zero choices."
                )


            choice = response.choices[0]

            message = choice.message

            text = message.content


            # Se GPT-OSS ha usato i token nel reasoning ma non ha prodotto una risposta finale,aumentiamo il budget e riproviamo.
            if text is None or not str(text).strip():

                finish_reason = getattr(
                    choice,
                    "finish_reason",
                    None
                )

                print(
                    "   Risposta senza content."
                )

                print(
                    "   finish_reason:",
                    finish_reason
                )

                current_max_tokens *= 2

                print(
                    "   Riprovo con max_tokens =",
                    current_max_tokens
                )

                time.sleep(2)

                continue


            return response


        #rate limit

        except RateLimitError as e:

            wait_time = 10

            try:

                retry_after = (
                    e.response.headers.get(
                        "retry-after"
                    )
                )

                if retry_after is not None:

                    wait_time = (
                        float(retry_after)
                        + 1
                    )

            except Exception:
                pass


            print(
                f"   Rate limit. "
                f"Attendo {wait_time:.1f}s..."
            )

            time.sleep(
                wait_time
            )


        #time out

        except (
            APIConnectionError,
            APITimeoutError
        ) as e:

            wait_time = min(
                5 * attempt,
                30
            )

            print(
                f" Connessione/timeout: {e}"
            )

            print(
                f" Riprovo tra {wait_time}s..."
            )

            time.sleep(
                wait_time
            )


        #errori vari

        except APIStatusError as e:

            if e.status_code in [
                408,
                409,
                429,
                500,
                502,
                503,
                504
            ]:

                wait_time = min(
                    5 * attempt,
                    30
                )

                print(
                    f"   HTTP {e.status_code}. "
                    f"Riprovo tra {wait_time}s..."
                )

                time.sleep(
                    wait_time
                )


            else:

                print(
                    "\n ERRORE OPENROUTER"
                )

                print(
                    "Status:",
                    e.status_code
                )

                print(e)

                raise


        except Exception as e:

            print(
                f" Errore: {e}"
            )

            if attempt == MAX_RETRIES:
                raise

            wait_time = min(
                3 * attempt,
                20
            )

            print(
                f" Riprovo tra {wait_time}s..."
            )

            time.sleep(
                wait_time
            )


    raise RuntimeError(
        "Chiamata fallita dopo tutti i tentativi."
    )

def parse_json(text):

    match = re.search(
        r"\{.*?\}",
        text,
        re.DOTALL
    )

    if not match:

        raise ValueError(
            f"JSON non trovato nella risposta: {text}"
        )


    return json.loads(
        match.group(0)
    )

def get_decision(text):

    text = str(text).strip()

    match = re.search(
        r"\b([AB])\b",
        text
    )

    if not match:

        raise ValueError(
            f"Nessuna decisione A/B trovata: {text}"
        )


    return match.group(1)

def normalize_token(token):

    token = str(token)

    token = token.strip()

    token = token.replace(
        '"',
        ''
    )

    token = token.replace(
        "'",
        ''
    )

    token = token.strip().upper()


    if token == "A":
        return "A"

    if token == "B":
        return "B"

    return None

def extract_logprobs(response):

    result = {
        "logprob_A": None,
        "logprob_B": None,
        "prob_A": None,
        "prob_B": None
    }


    logprobs = (
        response
        .choices[0]
        .logprobs
    )


    if logprobs is None:
        return result


    content = logprobs.content


    if not content:
        return result


    # Cerchiamo il primo token generato che corrisponde ad A oppure B

    target_position = None


    for position in content:

        token = normalize_token(
            position.token)

        if token in [
            "A",
            "B"
        ]:

            target_position = position
            break


    if target_position is None:
        return result


    # Token realmente generato

    generated = normalize_token(
        target_position.token)


    if generated == "A":

        result["logprob_A"] = (
            target_position.logprob )


    if generated == "B":

        result["logprob_B"] = (
            target_position.logprob)


    # Alternative nei top_logprobs

    for alternative in (
        target_position.top_logprobs
        or []
    ):

        token = normalize_token(
            alternative.token
        )


        if token == "A":

            result["logprob_A"] = (
                alternative.logprob
            )


        elif token == "B":

            result["logprob_B"] = (
                alternative.logprob
            )


    lpA = result[
        "logprob_A"
    ]

    lpB = result[
        "logprob_B"
    ]


    # Convertiamo in probabilità condizionate alle sole alternative A/B

    if (
        lpA is not None
        and
        lpB is not None
    ):

        pA = math.exp(lpA)

        pB = math.exp(lpB)


        result[
            "prob_A"
        ] = (
            pA
            /
            (pA + pB)
        )


        result[
            "prob_B"
        ] = (
            pB
            /
            (pA + pB)
        )


    return result

